# helper: a project in a temporary working directory with a config.yaml and a
# zip file of LiDAR point clouds (LAZ) that cannot be read into R
local_other_project <- function(env = parent.frame()) {

  project_dir <- withr::local_tempdir(.local_envir = env)
  withr::local_dir(project_dir, .local_envir = env)

  yaml::write_yaml(
    list(
      scope       = "knb-lter-cap",
      identifier  = 1,
      baseURL     = "https://example.org/data/",
      title       = "otherEntity templates dataset",
      project     = "gios",
      maintenance = "none"
    ),
    "config.yaml"
  )

  write_placeholder_zip(
    zip_file = "lidar_tiles.zip",
    files    = c("tile_w0384n3742.laz", "tile_w0384n3743.laz"),
    contents = charToRaw("LASF")
  )

  project_dir

}

# helper: write a zip file of placeholder files
write_placeholder_zip <- function(zip_file, files, contents) {

  staging_dir <- withr::local_tempdir()
  purrr::walk(files, ~ writeBin(contents, file.path(staging_dir, .x)))

  utils::zip(
    zipfile = file.path(getwd(), zip_file),
    files   = file.path(staging_dir, files),
    flags   = "-jq"
  )

}

# helper: read a template in either the block scalar or plain yaml format
read_template <- function(path) {

  template <- yaml::yaml.load_file(path)
  if (is.character(template)) {
    template <- yaml::yaml.load(template)
  }
  template

}

laz_attributes <- c("X", "Y", "Z", "Classification", "GpsTime", "PointSourceId")
laz_classes    <- c("numeric", "numeric", "numeric", "factor", "numeric", "character")

# helper: annotate the LAZ templates as a user would, retaining the block
# scalar format written by capeml
annotate_laz <- function() {

  attrs <- read_template("lidar_tiles_attrs.yaml")
  attrs <- purrr::map(attrs, function(attribute) {
    attribute$attributeDefinition <- paste("definition of", attribute$attributeName)
    attribute
  })
  attrs$X$unit       <- "meter"
  attrs$Y$unit       <- "meter"
  attrs$Z$unit       <- "meter"
  attrs$Z$minimum    <- 0
  attrs$GpsTime$unit <- "second"
  yaml::write_yaml(yaml::as.yaml(attrs), "lidar_tiles_attrs.yaml")

  fcts <- read_template("lidar_tiles_factors.yaml")
  fcts[[1]]$attribute$levels <- purrr::map(fcts[[1]]$attribute$levels, function(level) {
    level$definition <- paste("LAS class", level$code)
    level
  })
  yaml::write_yaml(yaml::as.yaml(fcts), "lidar_tiles_factors.yaml")

}

write_laz_templates <- function() {

  capeml::write_other_attributes(
    target_file    = "lidar_tiles.zip",
    attributes     = laz_attributes,
    column_classes = laz_classes
  )

  capeml::write_other_factors(
    target_file = "lidar_tiles.zip",
    factors     = list(Classification = c("2", "5"))
  )

}


testthat::test_that("write_other_attributes writes the fields of each class", {

  local_other_project()
  metadata_dir <- file.path(withr::local_tempdir(), "metadata")

  path <- capeml::write_other_attributes(
    target_file    = "lidar_tiles.zip",
    attributes     = laz_attributes,
    column_classes = laz_classes,
    metadata_path  = metadata_dir
  )

  testthat::expect_identical(path, file.path(metadata_dir, "lidar_tiles_attrs.yaml"))
  testthat::expect_match(readLines(path)[[1]], "^# metadata template generated by capeml")

  attrs <- read_template(path)

  testthat::expect_named(attrs, laz_attributes)
  testthat::expect_identical(attrs$Classification$columnClasses, "factor")
  testthat::expect_identical(attrs$X$unit, "")
  testthat::expect_identical(attrs$X$numberType, "real")
  testthat::expect_identical(attrs$PointSourceId$definition, "")
  testthat::expect_true(all(purrr::map_chr(attrs, "attributeDefinition") == ""))

  # LAZ point records do not include dates; a flight log in a zip file
  # exercises the Date class

  date_path <- capeml::write_other_attributes(
    target_file    = "flight_log.zip",
    attributes     = "acquisition_date",
    column_classes = "Date",
    metadata_path  = metadata_dir
  )

  testthat::expect_identical(read_template(date_path)$acquisition_date$formatString, "")

})


testthat::test_that("write_other_factors writes codes and placeholders", {

  local_other_project()

  capeml::write_other_factors(
    target_file = "lidar_tiles.zip",
    factors     = list(Classification = c("2", "5"), ScanChannel = character(0))
  )

  fcts <- read_template("lidar_tiles_factors.yaml")

  testthat::expect_identical(
    purrr::map_chr(fcts[[1]]$attribute$levels, "code"),
    c("2", "5")
  )
  testthat::expect_identical(fcts[[2]]$attribute$attributeName, "ScanChannel")
  testthat::expect_identical(fcts[[2]]$attribute$levels[[1]], list(code = "", definition = ""))

})


testthat::test_that("template writers validate their inputs", {

  local_other_project()

  testthat::expect_error(capeml::write_other_attributes("lidar_tiles.zip"), "names of the attributes")
  testthat::expect_error(
    capeml::write_other_attributes("lidar_tiles.zip", c("X", "Y"), "integer"),
    "column_classes must be one of"
  )
  testthat::expect_error(
    capeml::write_other_attributes("lidar_tiles.zip", c("X", "Y", "Z"), c("numeric", "factor")),
    "one column class"
  )
  testthat::expect_error(capeml::write_other_attributes("lidar_tiles.zip", c("X", "X")), "unique")
  testthat::expect_error(capeml::write_other_factors("lidar_tiles.zip", c("2", "5")), "named list")
  testthat::expect_error(
    capeml::write_other_factors("lidar_tiles.zip", list(Classification = c("2", "2"))),
    "unique within each factor"
  )

  capeml::write_other_attributes("lidar_tiles.zip", "X")
  testthat::expect_error(capeml::write_other_attributes("lidar_tiles.zip", "X"), "already exists")
  testthat::expect_no_error(capeml::write_other_attributes("lidar_tiles.zip", "X", overwrite = TRUE))

})


testthat::test_that("a zip of LAZ files with attributes and factors is schema-valid EML", {

  local_other_project()
  write_laz_templates()
  annotate_laz()

  laz_OE <- capeml::create_otherEntity(
    target_file_or_directory = "lidar_tiles.zip",
    description              = "classified LiDAR point cloud tiles"
  )

  attribute_names <- purrr::map_chr(laz_OE$attributeList$attribute, "attributeName")
  testthat::expect_identical(attribute_names, laz_attributes)

  # a zip without a shapefile is documented by its extension
  testthat::expect_identical(
    laz_OE$physical$dataFormat$externallyDefinedFormat$formatName,
    "zip"
  )

  eml <- EML::eml$eml(
    packageId = "knb-lter-cap.1.1",
    system    = "knb",
    dataset   = EML::eml$dataset(
      title       = "otherEntity templates dataset",
      creator     = list(individualName = list(surName = "Researcher")),
      contact     = list(individualName = list(surName = "Researcher")),
      otherEntity = list(laz_OE)
    )
  )

  testthat::expect_true(EML::eml_validate(eml))

})


testthat::test_that("create_otherEntity lists blank required fields", {

  local_other_project()
  write_laz_templates()

  error <- testthat::expect_error(
    capeml::create_otherEntity(
      target_file_or_directory = "lidar_tiles.zip",
      description              = "classified LiDAR point cloud tiles"
    ),
    "incomplete attribute or factor metadata for 'lidar_tiles'"
  )

  testthat::expect_match(conditionMessage(error), "X: attributeDefinition is blank")
  testthat::expect_match(conditionMessage(error), "X: unit is blank")
  testthat::expect_match(conditionMessage(error), "Classification: factor definition is blank")

})


testthat::test_that("create_otherEntity requires a formatString for Date attributes", {

  local_other_project()
  write_placeholder_zip("flight_log.zip", "flight_log.csv", charToRaw("acquisition_date\n"))

  capeml::write_other_attributes("flight_log.zip", "acquisition_date", "Date")
  attrs <- read_template("flight_log_attrs.yaml")
  attrs$acquisition_date$attributeDefinition <- "date of LiDAR acquisition"
  yaml::write_yaml(yaml::as.yaml(attrs), "flight_log_attrs.yaml")

  testthat::expect_error(
    capeml::create_otherEntity(
      target_file_or_directory = "flight_log.zip",
      description              = "LiDAR flight log"
    ),
    "acquisition_date: formatString is blank"
  )

})


testthat::test_that("create_otherEntity reads hand-written plain yaml templates", {

  local_other_project()

  yaml::write_yaml(
    list(
      Z = list(
        attributeName       = "Z",
        attributeDefinition = "elevation of the LiDAR point",
        unit                = "meter",
        numberType          = "real",
        columnClasses       = "numeric"
      ),
      PointSourceId = list(
        attributeName       = "PointSourceId",
        attributeDefinition = "flight line of the LiDAR point",
        columnClasses       = "character"
      )
    ),
    "lidar_tiles_attrs.yaml"
  )

  laz_OE <- capeml::create_otherEntity(
    target_file_or_directory = "lidar_tiles.zip",
    description              = "classified LiDAR point cloud tiles",
    project_naming           = FALSE
  )

  testthat::expect_length(laz_OE$attributeList$attribute, 2)
  testthat::expect_identical(
    laz_OE$attributeList$attribute[[1]]$measurementScale$ratio$unit$standardUnit,
    "meter"
  )

})


testthat::test_that("create_otherEntity documents a factors-only template", {

  local_other_project()

  capeml::write_other_factors("lidar_tiles.zip", list(Classification = c("2", "5")))
  fcts <- read_template("lidar_tiles_factors.yaml")
  fcts[[1]]$attribute$levels[[1]]$definition <- "ground"
  fcts[[1]]$attribute$levels[[2]]$definition <- "high vegetation"
  yaml::write_yaml(fcts, "lidar_tiles_factors.yaml")

  laz_OE <- capeml::create_otherEntity(
    target_file_or_directory = "lidar_tiles.zip",
    description              = "classified LiDAR point cloud tiles",
    project_naming           = FALSE,
    entity_value_description = "LAS classification code"
  )

  attribute <- laz_OE$attributeList$attribute[[1]]
  testthat::expect_identical(attribute$attributeName, "Classification")
  testthat::expect_identical(attribute$attributeDefinition, "LAS classification code")

})
